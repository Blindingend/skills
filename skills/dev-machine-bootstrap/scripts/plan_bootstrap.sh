#!/usr/bin/env bash
set -euo pipefail

target="${1:-local}"
skill_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
inspect_script="$skill_dir/scripts/inspect_host.sh"

report="$("$inspect_script" "$target")"

pkg_manager="$(printf "%s\n" "$report" | awk '/^__PKG_MANAGER__/{getline; print; exit}')"
sudo_state="$(printf "%s\n" "$report" | awk '/^__SUDO__/{getline; print; exit}')"

echo "__PLAN_TARGET__"
echo "$target"
echo "__PLAN_MODE__"
if [[ "$sudo_state" == "NOPASSWD" ]]; then
  echo "apply-sudo"
else
  echo "apply-user"
fi
echo "__FACTS__"
printf "%s\n" "$report"
echo "__RECOMMENDED_STEPS__"
echo "1. Back up any existing remote dotfiles before replacement."
echo "2. Copy a safe shared zshrc generated by render_safe_zshrc.sh."
echo "3. Copy shared tmux, theme, and alias files only after checking they contain no machine-specific paths."
if [[ "$sudo_state" == "NOPASSWD" ]]; then
  case "$pkg_manager" in
    */dnf|*/yum)
      echo "4. Install zsh tmux and optionally ripgrep via sudo dnf."
      echo "5. Install fzf and pixi in user space."
      echo "6. Optionally run chsh to switch the default shell to zsh."
      ;;
    */apt)
      echo "4. Install zsh tmux and optionally ripgrep via sudo apt."
      echo "5. Install fzf and pixi in user space."
      echo "6. Optionally run chsh to switch the default shell to zsh."
      ;;
    *)
      echo "4. Install base packages with the detected package manager."
      echo "5. Install fzf and pixi in user space."
      ;;
  esac
else
  echo "4. Skip system package installation until sudo is available."
  echo "5. Install fzf and pixi in user space if git/curl/wget and tar are available."
  echo "6. Keep the default shell unchanged until zsh is installed."
fi
echo "7. Re-run inspect_host.sh to verify the final state."
